fn probe_command_version(path: &Path, args: &[&str], context: &ProjectContext) -> Option<String> {
    let args = args
        .iter()
        .map(|value| value.to_string())
        .collect::<Vec<_>>();
    let output = process::run(path, &args, &context.root).ok()?;
    if !output.status.success() {
        return None;
    }
    output
        .stdout
        .lines()
        .find_map(|line| extract_version_token(line.trim()))
}

fn extract_version_token(line: &str) -> Option<String> {
    line.split_whitespace()
        .find(|token| token.chars().next().is_some_and(|c| c.is_ascii_digit()))
        .map(|value| value.trim_start_matches('v').to_string())
        .or_else(|| {
            line.split_whitespace()
                .last()
                .map(|value| value.trim_start_matches('v').to_string())
        })
}

fn probe_gdtest_harness_version(
    context: &ProjectContext,
    _config: &GdsuiteConfig,
) -> Option<String> {
    let harness_path = context.root.join(GDTEST_HARNESS_PATH);
    let body = fs::read_to_string(harness_path).ok()?;
    extract_quoted_assignment(&body, "HARNESS_VERSION")
}

fn probe_gdhealth_schema_version(path: &Path, context: &ProjectContext) -> Option<u32> {
    for args in [["--schema-version"], ["schema-version"]] {
        let args = args
            .iter()
            .map(|value| value.to_string())
            .collect::<Vec<_>>();
        let output = process::run(path, &args, &context.root).ok()?;
        if !output.status.success() {
            continue;
        }
        if let Some(value) = output
            .stdout
            .lines()
            .find_map(|line| line.trim().parse::<u32>().ok())
        {
            return Some(value);
        }
    }
    None
}

fn extract_quoted_assignment(body: &str, name: &str) -> Option<String> {
    for line in body.lines() {
        let line = line.trim();
        if !line.contains(name) {
            continue;
        }
        let start = line.find('"')?;
        let end = line[start + 1..].find('"')?;
        return Some(line[start + 1..start + 1 + end].to_string());
    }
    None
}

fn normalize_spec(spec: &str) -> String {
    spec.trim_start_matches('=').trim().to_string()
}

fn normalize_version(version: &str) -> String {
    version.trim().trim_start_matches('v').to_string()
}

/// gdtoolkit's configuration files that `gdtidy.toml` has no section for yet:
/// a gdlintrc without `[lint]`, a gdformatrc without `[fmt]`. gdtidy reads
/// neither file, so each is converted once.
pub fn unconverted_configs(context: &ProjectContext) -> Vec<PathBuf> {
    let read = |name: &str| -> Option<toml::Table> {
        fs::read_to_string(context.root.join(name))
            .ok()
            .and_then(|text| text.parse().ok())
    };
    let files = [read("gdtidy.toml"), read("gdsuite.toml")];
    let has = |section: &str| {
        files
            .iter()
            .flatten()
            .any(|table| table.contains_key(section))
    };
    let mut found = Vec::new();
    for (names, section) in [
        (["gdlintrc", ".gdlintrc"], "lint"),
        (["gdformatrc", ".gdformatrc"], "fmt"),
    ] {
        if has(section) {
            continue;
        }
        if let Some(path) = names
            .into_iter()
            .map(|name| context.root.join(name))
            .find(|path| path.is_file())
        {
            found.push(path);
        }
    }
    found
}

/// What `gdtidy migrate` converted, and where it wrote the result.
pub struct ToolConfigConversion {
    pub files: Vec<String>,
    /// `gdsuite.toml` when the project has one and no `gdtidy.toml`.
    pub target: String,
    /// gdtidy's notes, such as rules that moved to Godot.
    pub notes: Vec<String>,
}

/// Convert the project's gdlintrc and gdformatrc with `gdtidy migrate`, which
/// adds `[lint]` and `[fmt]` to gdsuite.toml (or to an existing gdtidy.toml)
/// and only the sections it does not have, so lint and fmt keep the
/// project's settings. `None` when there was nothing to convert.
pub fn convert_tool_configs(
    context: &ProjectContext,
    gdtidy: &Path,
) -> Result<Option<ToolConfigConversion>> {
    let files = unconverted_configs(context);
    if files.is_empty() {
        return Ok(None);
    }
    let names: Vec<String> = files
        .iter()
        .map(|path| {
            path.file_name()
                .map(|name| name.to_string_lossy().into_owned())
                .unwrap_or_default()
        })
        .collect();
    // Bare names, run from the project root: gdtidy names the converted files
    // in the header of gdtidy.toml, which is committed.
    let mut args = vec!["migrate".to_string()];
    args.extend(names.iter().cloned());
    let output = process::run(gdtidy, &args, &context.root)?;
    if !output.status.success() {
        return Err(anyhow!(
            "could not convert {}: {}",
            names.join(" and "),
            output.stderr.trim()
        ));
    }
    // Converting gdlintrc and gdformatrc together, gdtidy notes an exclusion
    // both files share once per file; show each note once.
    let mut notes: Vec<String> = Vec::new();
    let mut target = "gdtidy.toml".to_string();
    for note in output
        .stderr
        .lines()
        .filter_map(|line| line.trim().strip_prefix("gdtidy: "))
    {
        if let Some(wrote) = note.strip_prefix("wrote ") {
            if let Some((path, _)) = wrote.split_once(" from ") {
                target = path.to_string();
            }
            continue;
        }
        if !notes.iter().any(|seen| seen == note) {
            notes.push(note.to_string());
        }
    }
    Ok(Some(ToolConfigConversion {
        files: names,
        target,
        notes,
    }))
}

pub fn install_gdtest_addons(
    context: &ProjectContext,
    config: &GdsuiteConfig,
) -> Result<AddonInstallReport> {
    let source_root = resolved_source_root(context, &config.tools.gdtest_source, "gdtest")?;
    let runtime_source = source_root.join("addons").join("gdtest");
    if !runtime_source.exists() {
        return Err(anyhow!(
            "gdtest runtime addon source missing at {}",
            runtime_source.display()
        ));
    }

    let mut report = AddonInstallReport::default();
    // A project's addon files from another harness version are not user
    // edits: gdtest refuses to run with them. Replace them, after a backup.
    let harness_name = Path::new(GDTEST_HARNESS_PATH).file_name().unwrap();
    let source_version = harness_version_of(&runtime_source.join(harness_name));
    let project_version = harness_version_of(&context.root.join(GDTEST_HARNESS_PATH));
    let backup_dir = match (&project_version, &source_version) {
        (Some(from), Some(to)) if from != to => {
            let backup_dir = context
                .gdsuite_dir
                .join("backups")
                .join(format!("gdtest-addons-{from}"));
            report.upgrade = Some(AddonUpgrade {
                from_version: from.clone(),
                to_version: to.clone(),
                backup_dir: backup_dir.clone(),
                replaced: Vec::new(),
            });
            Some(backup_dir)
        }
        _ => None,
    };
    let runtime_target_dir = harness_parent_dir(GDTEST_HARNESS_PATH);
    let runtime_res_dir = res_dir_from_rel_path(&runtime_target_dir);
    install_addon_dir(
        &runtime_source,
        &context.root.join(&runtime_target_dir),
        AddonTarget {
            project_root: &context.root,
            backup_dir: backup_dir.as_deref(),
        },
        &mut report,
        |relative, contents| rewrite_runtime_asset(relative, contents, &runtime_res_dir),
    )?;

    let editor_source = source_root.join("addons").join("gdtest_editor");
    if !editor_source.exists() {
        return Err(anyhow!(
            "gdtest editor addon source missing at {}",
            editor_source.display()
        ));
    }
    let editor_res_dir = res_dir_from_rel_path(Path::new(GDTEST_EDITOR_PLUGIN_DIR));
    install_addon_dir(
        &editor_source,
        &context.root.join(GDTEST_EDITOR_PLUGIN_DIR),
        AddonTarget {
            project_root: &context.root,
            backup_dir: backup_dir.as_deref(),
        },
        &mut report,
        |relative, contents| rewrite_editor_asset(relative, contents, &editor_res_dir),
    )?;

    Ok(report)
}

fn harness_version_of(harness: &Path) -> Option<String> {
    let body = fs::read_to_string(harness).ok()?;
    extract_quoted_assignment(&body, "HARNESS_VERSION")
}

/// Where addon files go, and where to back up the files an upgrade replaces
/// (`None` keeps files that differ, as the user's edits).
#[derive(Clone, Copy)]
struct AddonTarget<'a> {
    project_root: &'a Path,
    backup_dir: Option<&'a Path>,
}

fn install_addon_dir(
    source_dir: &Path,
    target_dir: &Path,
    target: AddonTarget<'_>,
    report: &mut AddonInstallReport,
    rewrite: impl Fn(&Path, &str) -> String + Copy,
) -> Result<()> {
    for entry in fs::read_dir(source_dir)
        .with_context(|| format!("failed to read addon source {}", source_dir.display()))?
    {
        let entry = entry?;
        let source_path = entry.path();
        let relative = source_path.strip_prefix(source_dir).unwrap();
        let target_path = target_dir.join(relative);

        if entry.file_type()?.is_dir() {
            fs::create_dir_all(&target_path)
                .with_context(|| format!("failed to create {}", target_path.display()))?;
            install_addon_dir(&source_path, &target_path, target, report, rewrite)?;
            continue;
        }

        let contents = fs::read_to_string(&source_path)
            .with_context(|| format!("failed to read {}", source_path.display()))?;
        let rewritten = rewrite(relative, &contents);
        if let Some(parent) = target_path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("failed to create {}", parent.display()))?;
        }

        if target_path.exists() {
            let current = fs::read_to_string(&target_path)
                .with_context(|| format!("failed to read {}", target_path.display()))?;
            if current == rewritten {
                continue;
            }
            let Some(backup_dir) = target.backup_dir else {
                report.skipped_modified.push(target_path);
                continue;
            };
            let relative_to_project = target_path
                .strip_prefix(target.project_root)
                .unwrap_or(&target_path);
            let backup_path = backup_dir.join(relative_to_project);
            if let Some(parent) = backup_path.parent() {
                fs::create_dir_all(parent)
                    .with_context(|| format!("failed to create {}", parent.display()))?;
            }
            fs::write(&backup_path, current)
                .with_context(|| format!("failed to back up {}", target_path.display()))?;
            if let Some(upgrade) = report.upgrade.as_mut() {
                upgrade.replaced.push(target_path.clone());
            }
        }

        fs::write(&target_path, rewritten)
            .with_context(|| format!("failed to write {}", target_path.display()))?;
        report.installed_files += 1;
    }

    Ok(())
}

fn rewrite_runtime_asset(relative: &Path, contents: &str, runtime_res_dir: &str) -> String {
    let runtime_prefix = join_res_path(runtime_res_dir, "gdunit4_chain.gd");
    let compat_prefix = join_res_path(runtime_res_dir, "gdunit4_compat.gd");
    match relative.to_string_lossy().replace('\\', "/").as_str() {
        "gdtest_worker.gd" => contents
            .replace("res://addons/gdtest/gdunit4_chain.gd", &runtime_prefix)
            .replace("res://addons/gdtest/gdunit4_compat.gd", &compat_prefix),
        "gdunit4_compat.gd" => {
            contents.replace("res://addons/gdtest/gdunit4_chain.gd", &runtime_prefix)
        }
        _ => contents.to_string(),
    }
}

fn rewrite_editor_asset(relative: &Path, contents: &str, editor_res_dir: &str) -> String {
    match relative.to_string_lossy().replace('\\', "/").as_str() {
        "plugin.gd" => contents.replace(
            "res://addons/gdtest_editor/test_panel.gd",
            &join_res_path(editor_res_dir, "test_panel.gd"),
        ),
        _ => contents.to_string(),
    }
}

fn harness_parent_dir(harness: &str) -> PathBuf {
    Path::new(harness)
        .parent()
        .map(Path::to_path_buf)
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or_else(|| PathBuf::from("."))
}

fn res_dir_from_rel_path(path: &Path) -> String {
    let normalized = path.display().to_string().replace('\\', "/");
    if normalized == "." || normalized.is_empty() {
        "res://".to_string()
    } else {
        format!("res://{}", normalized.trim_end_matches('/'))
    }
}

fn join_res_path(base: &str, file: &str) -> String {
    if base.ends_with('/') {
        format!("{base}{file}")
    } else {
        format!("{base}/{file}")
    }
}

impl InstallPlan {
    pub fn get(&self, tool: &str) -> &ToolAcquireSpec {
        match tool {
            "gdtest" => &self.gdtest,
            "gdhealth" => &self.gdhealth,
            "gdtypecheck" => &self.gdtypecheck,
            "gdtidy" => &self.gdtidy,
            _ => panic!("unknown tool {tool}"),
        }
    }
}

/// A tool whose installed source is not the one gdsuite.toml (or, for a tool
/// it doesn't pin, this gdsuite) asks for, such as after updating gdsuite.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ToolDrift {
    pub tool: &'static str,
    pub wanted: String,
    pub installed: String,
}

impl ToolDrift {
    pub fn message(&self) -> String {
        // Release and crates.io sources are gone: update removes them.
        let fix = if self.wanted.starts_with("github:") || self.wanted.starts_with("crate:") {
            "gdsuite update"
        } else {
            "gdsuite setup"
        };
        format!(
            "{}: {} is installed, but this project now uses {}; run `{fix}`",
            self.tool, self.installed, self.wanted
        )
    }
}

pub fn installed_drift(context: &ProjectContext, config: &GdsuiteConfig) -> Vec<ToolDrift> {
    let Ok(state) = InstalledState::load(&context.installation_path) else {
        return Vec::new();
    };
    let plan = install_plan(config);
    crate::config::TOOL_NAMES
        .into_iter()
        .filter_map(|tool| {
            let installed = match tool {
                "gdtest" => &state.tools.gdtest,
                "gdhealth" => &state.tools.gdhealth,
                "gdtypecheck" => &state.tools.gdtypecheck,
                _ => &state.tools.gdtidy,
            };
            let wanted = plan.get(tool);
            (installed.requested != *wanted).then(|| ToolDrift {
                tool,
                wanted: wanted.render_requested(),
                installed: installed.requested.render_requested(),
            })
        })
        .collect()
}

/// gdsuite's own tools pinned in `[tools]` to a release other than the one
/// this gdsuite was tested with: `(tool, pinned tag, tested tag)`.
pub fn outdated_pins(config: &GdsuiteConfig) -> Vec<(&'static str, String, String)> {
    let release = release_manifest();
    config
        .tools
        .pinned()
        .into_iter()
        .filter_map(|(tool, source)| {
            let tag = format!("v{}", release.tool(tool)?.version());
            let pinned = source.strip_prefix(&own_release_prefix(tool))?;
            (pinned != tag).then(|| (tool, pinned.to_string(), tag))
        })
        .collect()
}

/// Where each tool reads its settings: `(label, source)`, the source being
/// a `gdsuite.toml` section, the tool's own file, or its defaults.
pub fn settings_sources(context: &ProjectContext) -> Vec<(&'static str, String)> {
    let sections: Vec<String> = fs::read_to_string(&context.config_path)
        .ok()
        .and_then(|text| text.parse::<toml::Table>().ok())
        .map(|table| table.keys().cloned().collect())
        .unwrap_or_default();
    let source = |keys: &[&str], file: &str| {
        let found: Vec<String> = keys
            .iter()
            .filter(|key| sections.iter().any(|section| section == *key))
            .map(|key| format!("[{key}]"))
            .collect();
        if !found.is_empty() {
            format!("gdsuite.toml {}", found.join(" "))
        } else if context.root.join(file).exists() {
            file.to_string()
        } else {
            "defaults".to_string()
        }
    };
    vec![
        ("test", source(&["test"], "gdtest.toml")),
        ("health", source(&["health"], "gdhealth.toml")),
        ("fmt_lint", source(&["fmt", "lint"], "gdtidy.toml")),
    ]
}

/// The start of a `[tools]` source that pins one of gdsuite's own tools to
/// a GitHub release: `github:q-rault/gdtest@`.
pub fn own_release_prefix(tool: &str) -> String {
    format!("github:q-rault/{tool}@")
}

